import { NextRequest, NextResponse } from 'next/server';
import { QueryTypes } from 'sequelize';
import { sequelize, connectDB } from '@/lib/sequelize';
import { requireAuth, isAuthError } from '@/lib/apiAuth';
import { isCeo } from '@/lib/roleChecks';

let dbReady = false;
async function ensureDB() {
  if (!dbReady) { await connectDB(); dbReady = true; }
}

export async function GET(request: NextRequest) {
  const auth = requireAuth(request);
  if (isAuthError(auth)) return auth;
  if (!isCeo(auth)) {
    return NextResponse.json({ error: 'CEO access required' }, { status: 403 });
  }

  await ensureDB();

  const versions = await sequelize.query(
    `SELECT version_id, version_name, notes, published_at, raw_data, last_synced_at
     FROM dm_gtm_version_history ORDER BY id DESC LIMIT 50`,
    { type: QueryTypes.SELECT }
  );

  return NextResponse.json({ versions });
}
