// Regenerates src/lib/brandLogo.ts (inline data URIs) from the CW Migration
// Advisor logo files in public/brand/. Receipts open in an about:blank window
// and agreements are stored as HTML, so relative image URLs would not resolve —
// the logos are embedded instead.
//   public/brand/cw-logo-horizontal.png  -> BRAND_LOGO_DATA_URI (header lockup)
//   public/brand/cw-logo-icon.png        -> BRAND_ICON_DATA_URI (footer triangle)
//   public/brand/cw-logo-stacked.png     -> BRAND_LOGO_STACKED_DATA_URI
// Replace the PNGs and re-run:  node scripts/generate-brand-logo.js
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const dir = path.join(__dirname, '..', 'public', 'brand');
const uri = async (file, width) => {
  const buf = await sharp(path.join(dir, file)).resize({ width, withoutEnlargement: true }).png({ compressionLevel: 9 }).toBuffer();
  return `data:image/png;base64,${buf.toString('base64')}`;
};

(async () => {
  const out = `// Generated by scripts/generate-brand-logo.js — do not edit by hand.
export const BRAND_LOGO_DATA_URI = '${await uri('cw-logo-horizontal.png', 640)}';
export const BRAND_ICON_DATA_URI = '${await uri('cw-logo-icon.png', 96)}';
export const BRAND_LOGO_STACKED_DATA_URI = '${await uri('cw-logo-stacked.png', 480)}';
`;
  fs.writeFileSync(path.join(__dirname, '..', 'src', 'lib', 'brandLogo.ts'), out);
  console.log('brandLogo.ts written', out.length, 'chars');
})();
