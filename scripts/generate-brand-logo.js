// Regenerates src/lib/brandLogo.ts (inline data URI) from public/brand-logo.png.
// Receipts open in an about:blank window and agreements are stored as HTML, so
// relative image URLs would not resolve — the logo is embedded instead.
// Replace public/brand-logo.png with the final CW Migration logo and re-run:
//   node scripts/generate-brand-logo.js
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

(async () => {
  const src = path.join(__dirname, '..', 'public', 'brand-logo.png');
  const buf = await sharp(src).resize({ width: 420, withoutEnlargement: true }).png({ compressionLevel: 9 }).toBuffer();
  const out = `// Generated by scripts/generate-brand-logo.js — do not edit by hand.\nexport const BRAND_LOGO_DATA_URI = 'data:image/png;base64,${buf.toString('base64')}';\n`;
  fs.writeFileSync(path.join(__dirname, '..', 'src', 'lib', 'brandLogo.ts'), out);
  console.log('brandLogo.ts written', buf.length, 'bytes');
})();
